#pragma once
#include <array>
#include <cstdint>
#include <memory>
#include <span>

namespace civ5::runtime {class BnwWorldViewSourceOperationLoan;}
namespace civ5::ui::detail {
class BnwOriginalNonFontDeviceInitializer;

// Only the actual resource0 stage of the closed device initializer can create
// this immutable image. It carries no native resource ID, GPU name, sampler,
// successful device-constructor return, resource-bank or Draw permission.
class BnwOriginalGeneratedResourceImageLoan final {
    friend class BnwOriginalNonFontDeviceInitializer;
    struct Impl;
    const std::shared_ptr<Impl> impl_;
    explicit BnwOriginalGeneratedResourceImageLoan(std::shared_ptr<Impl>);
    static std::shared_ptr<const BnwOriginalGeneratedResourceImageLoan>
    create_resource0_owned(const BnwOriginalNonFontDeviceInitializer&,
        const runtime::BnwWorldViewSourceOperationLoan&);
public:
    struct Bgra8LevelView final {
        const std::uint32_t width,height,row_pitch;
        const std::span<const std::uint8_t> bgra;
    };
    BnwOriginalGeneratedResourceImageLoan(const BnwOriginalGeneratedResourceImageLoan&)=delete;
    BnwOriginalGeneratedResourceImageLoan&operator=(const BnwOriginalGeneratedResourceImageLoan&)=delete;
    BnwOriginalGeneratedResourceImageLoan(BnwOriginalGeneratedResourceImageLoan&&)=delete;
    BnwOriginalGeneratedResourceImageLoan&operator=(BnwOriginalGeneratedResourceImageLoan&&)=delete;
    ~BnwOriginalGeneratedResourceImageLoan();

    void require_physical_without_callbacks()const;
    void require_source_owned(const runtime::BnwWorldViewSourceOperationLoan&)const;
    // Returns the canonical image control block. A consumer compares both
    // address and owner_before against its offered shared_ptr before use;
    // an aliasing shared_ptr with an unrelated owner is not admitted.
    std::shared_ptr<const BnwOriginalGeneratedResourceImageLoan>
    retain_owner_owned_without_callbacks()const;

    std::array<std::uint32_t,2> dimensions_owned(
        const runtime::BnwWorldViewSourceOperationLoan&)const;
    std::uint32_t original_d3d_format_owned(
        const runtime::BnwWorldViewSourceOperationLoan&)const;
    std::uint32_t original_level_count_owned(
        const runtime::BnwWorldViewSourceOperationLoan&)const;
    std::uint64_t original_initialization_epoch_owned(
        const runtime::BnwWorldViewSourceOperationLoan&)const;
    std::uint64_t creation_source_serial_owned(
        const runtime::BnwWorldViewSourceOperationLoan&)const;

    // Exact native little-endian A8R8G8B8 bytes: B,G,R,A. The seven levels
    // are independently filled, not averaged/generated by GL. Each owned row
    // is width*4 bytes. Views borrow storage from the SAME retained image.
    std::span<const Bgra8LevelView> bgra8_levels_owned(
        const runtime::BnwWorldViewSourceOperationLoan&)const;
    std::uint32_t row_pitch_owned(const runtime::BnwWorldViewSourceOperationLoan&,
        std::uint32_t level)const;
};
}
